export const generateProjectDescription = async ({ projectName, fieldName }: GenerateDescriptionRequest): Promise<string> => {
  try {
    console.log('Отправляем запрос к бэкенду...');
    const prompt = `Ты - опытный менеджер проектов, специализирующийся на написании профессиональных описаний проектов.
    Твоя задача - создать краткое, но информативное описание проекта "${projectName}" в направлении "${fieldName}". 
    Включи следующие аспекты:
    1. Основные цели и задачи проекта
    2. Ожидаемые результаты и их значимость
    3. Ключевые этапы реализации
    4. Потенциальные риски и способы их минимизации
    
    Описание должно быть структурированным, профессиональным и привлекающим внимание - 
    должно быть понятным как техническим специалистам, так и бизнес-заинтересованным лицам.`;

    const response = await axios.post(
      BACKEND_API_URL,
      {
        prompt,
        model: "yandexgpt-lite",
        temperature: 0.7,
        max_tokens: 1000
      },
      {
        headers: {
          'Authorization': `Bearer ${BACKEND_API_KEY}`,
          'Content-Type': 'application/json'
        },
        timeout: 30000 // 30 секунд таймаут
      }
    );

    console.log('Получен ответ от бэкенда:', response.data);

    if (!response.data || !response.data.text) {
      throw new Error('Неверный формат ответа от API');
    }

    return response.data.text;
  } catch (error: any) {
    console.error('Ошибка при генерации описания через API:', error);
    if (error.code === 'ERR_NETWORK') {
      console.error('Не удалось подключиться к серверу. Убедитесь, что сервер запущен на порту 3001');
    }
    if (error.response) {
      console.error('Детали ошибки:', {
        status: error.response.status,
        data: error.response.data
      });
    }
    console.log('Используем локальную генерацию как запасной вариант');
    return getRandomDescription(projectName, fieldName);
  }
}; 